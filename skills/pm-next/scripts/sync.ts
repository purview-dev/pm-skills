#!/usr/bin/env bun
// Keeps the PM branch mergeable under every pull request merge method
// (merge commit, squash, rebase). Dependency-free: node: and bun: only.
//
//   release  After an item branch is cut from a PM branch that is ahead of its
//            remote, move the PM branch back to the remote: the item branch
//            now carries those commits, so the PM branch never keeps them.
//   pull     Fast-forward the PM branch, or repair a diverged one: its
//            local-only commits (PM root only) are merged onto the remote with
//            a three-way tree merge. Work that was already delivered (by any
//            merge method) merges to nothing; anything else becomes one carry
//            commit. A conflict leaves the branch where it was.
//   driver   Register the merge driver that keeps <PM root>/planning.json,
//            a derived file, from conflicting in local merges.
//
// State-changing git commands used, and only these: fetch, merge --ff-only,
// branch -f, reset --keep, read-tree -m -u, add, commit, commit-tree, config.
// It never pushes, stashes, rebases, or runs --hard.

import { spawnSync } from "node:child_process";
import { appendFileSync, existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export interface SyncOptions {
  /** Repository root (any worktree of it). */
  root: string;
  /** PM root, repository-relative, for example `planning/`. */
  pmRoot: string;
  pmBranch: string;
  /** Remote name, or null when the repository has none. */
  remote: string | null;
}

export interface SyncResult {
  action: "none" | "fast-forward" | "released" | "repaired" | "carried" | "registered";
  /** Commits moved off the PM branch (release, repair, carry) or fast-forwarded. */
  moved: number;
  message: string;
  /** The carry commit, when one was made. */
  commit?: string;
}

/** A refusal: the PM branch is left exactly where it was. */
export class SyncError extends Error {}

/** Derived files: regenerated by pm-export, never merged. */
const DERIVED = ["planning.json", "planning.schema.json"];

interface Run {
  status: number;
  stdout: string;
  stderr: string;
}

function run(cwd: string, args: string[], env?: Record<string, string>): Run {
  const result = spawnSync("git", args, { cwd, encoding: "utf8", env: env ? { ...process.env, ...env } : process.env });
  return { status: result.status ?? 1, stdout: (result.stdout ?? "").trim(), stderr: (result.stderr ?? "").trim() };
}

function git(cwd: string, args: string[], env?: Record<string, string>): string {
  const result = run(cwd, args, env);
  if (result.status !== 0) throw new SyncError(`git ${args.join(" ")} failed: ${result.stderr || result.stdout}`);
  return result.stdout;
}

const dir = (pmRoot: string) => pmRoot.replace(/\\/g, "/").replace(/\/+$/, "");

/** The worktree path that has `branch` checked out, or null. */
function checkedOutAt(root: string, branch: string): string | null {
  let path: string | null = null;
  for (const line of git(root, ["worktree", "list", "--porcelain"]).split(/\r?\n/)) {
    if (line.startsWith("worktree ")) path = line.slice("worktree ".length);
    if (line === `branch refs/heads/${branch}`) return path;
  }
  return null;
}

interface Position {
  remoteRef: string;
  ahead: number;
  behind: number;
}

/** Fetch, then compare the PM branch with its remote. Null when there is nothing to compare with. */
function position(opts: SyncOptions): Position | null {
  if (!opts.remote) return null;
  git(opts.root, ["fetch", "-q", opts.remote, "--prune"]);
  const remoteRef = `${opts.remote}/${opts.pmBranch}`;
  if (run(opts.root, ["rev-parse", "-q", "--verify", `refs/remotes/${remoteRef}`]).status !== 0) return null;
  const [ahead, behind] = git(opts.root, ["rev-list", "--left-right", "--count", `${opts.pmBranch}...${remoteRef}`])
    .split(/\s+/)
    .map(Number);
  return { remoteRef, ahead: ahead ?? 0, behind: behind ?? 0 };
}

export function release(opts: SyncOptions): SyncResult {
  const at = position(opts);
  if (!at) return { action: "none", moved: 0, message: "no remote" };
  if (at.ahead === 0 && at.behind === 0) {
    return { action: "none", moved: 0, message: `${opts.pmBranch} already matches ${at.remoteRef}.` };
  }
  if (checkedOutAt(opts.root, opts.pmBranch)) {
    return { action: "none", moved: 0, message: `${opts.pmBranch} is checked out. Run release from the item branch.` };
  }
  if (run(opts.root, ["merge-base", "--is-ancestor", opts.pmBranch, "HEAD"]).status !== 0) {
    return { action: "none", moved: 0, message: `${opts.pmBranch} has commits the current branch does not carry; not moved.` };
  }
  git(opts.root, ["branch", "-f", opts.pmBranch, at.remoteRef]);
  return {
    action: "released",
    moved: at.ahead,
    message: `Moved ${at.ahead} PM commits from ${opts.pmBranch} to the item branch.`,
  };
}

/** A commit of `commit`'s tree with the derived files put back to their `base` state. */
function withoutDerived(root: string, pm: string, commit: string, base: string): string {
  const scratch = mkdtempSync(join(tmpdir(), "pm-sync-index-"));
  const env = { GIT_INDEX_FILE: join(scratch, "index") };
  try {
    git(root, ["read-tree", commit], env);
    for (const name of DERIVED) {
      const path = `${pm}/${name}`;
      const entry = git(root, ["ls-tree", base, "--", path]);
      if (entry) {
        const [mode, , blob] = entry.split(/\s+/);
        git(root, ["update-index", "--add", "--cacheinfo", `${mode},${blob},${path}`], env);
      } else {
        git(root, ["update-index", "--force-remove", "--", path], env);
      }
    }
    const tree = git(root, ["write-tree"], env);
    return git(root, ["commit-tree", tree, "-p", commit, "-m", "pm-sync: local PM changes without derived files"]);
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

const exportScript = () => resolve(dirname(fileURLToPath(import.meta.url)), "../../pm-export/scripts/export.ts");

/** Refresh the export in `worktree`. Best effort: the Markdown is the state. */
function refreshExport(worktree: string, pmRoot: string): boolean {
  if (!existsSync(join(worktree, dir(pmRoot), "planning.json")) || !existsSync(exportScript())) return false;
  const result = spawnSync(process.execPath, [exportScript(), "write", "--root", worktree, "--pm-root", pmRoot], { cwd: worktree, encoding: "utf8" });
  return result.status === 0;
}

export function pull(opts: SyncOptions): SyncResult {
  const pm = dir(opts.pmRoot);
  const at = position(opts);
  if (!at) return { action: "none", moved: 0, message: "no remote" };
  const { remoteRef, ahead, behind } = at;
  const worktree = checkedOutAt(opts.root, opts.pmBranch);

  if (ahead === 0 && behind === 0) return { action: "none", moved: 0, message: `${opts.pmBranch} is up to date.` };
  if (behind === 0) {
    return { action: "none", moved: 0, message: `${opts.pmBranch} is ${ahead} commits ahead of ${remoteRef}; nothing to pull.` };
  }
  if (ahead === 0) {
    if (worktree) git(worktree, ["merge", "-q", "--ff-only", remoteRef]);
    else git(opts.root, ["branch", "-f", opts.pmBranch, remoteRef]);
    return { action: "fast-forward", moved: behind, message: `${opts.pmBranch} fast-forwarded ${behind} commits.` };
  }

  // Diverged. Every local-only commit must stay inside the PM root.
  const outside = git(opts.root, ["log", "--format=", "--name-only", `${remoteRef}..${opts.pmBranch}`])
    .split(/\r?\n/)
    .filter((path) => path && !path.startsWith(`${pm}/`));
  if (outside.length > 0) {
    throw new SyncError(`${ahead} local commits on ${opts.pmBranch} touch paths outside ${pm}/ (${outside[0]}); not moved.`);
  }
  if (worktree && git(worktree, ["status", "--porcelain", "--", pm])) {
    throw new SyncError(`${opts.pmBranch} has uncommitted changes under ${pm}/ in ${worktree}; not moved.`);
  }

  const old = git(opts.root, ["rev-parse", opts.pmBranch]);
  const base = git(opts.root, ["merge-base", opts.pmBranch, remoteRef]);
  const local = withoutDerived(opts.root, pm, old, base);
  const merged = run(opts.root, ["merge-tree", "--write-tree", "--name-only", "--merge-base", base, remoteRef, local]);
  if (merged.status !== 0) {
    const conflicts = merged.stdout.split(/\r?\n/).slice(1).filter(Boolean).join(", ");
    throw new SyncError(
      `${opts.pmBranch} left at ${old}: carrying it onto ${remoteRef} (${git(opts.root, ["rev-parse", remoteRef])}) conflicts in ${conflicts || "the PM root"}.`,
    );
  }
  const tree = merged.stdout.split(/\r?\n/)[0]!;

  const restore = (reason: string): never => {
    if (worktree) run(worktree, ["reset", "-q", "--keep", old]);
    else run(opts.root, ["branch", "-f", opts.pmBranch, old]);
    throw new SyncError(`restored ${opts.pmBranch} to ${old}; ${reason}`);
  };

  if (tree === git(opts.root, ["rev-parse", `${remoteRef}^{tree}`])) {
    if (worktree) git(worktree, ["reset", "-q", "--keep", remoteRef]);
    else git(opts.root, ["branch", "-f", opts.pmBranch, remoteRef]);
    return {
      action: "repaired",
      moved: ahead,
      message: `${opts.pmBranch} repaired: ${ahead} delivered commits replaced by ${remoteRef}.`,
    };
  }

  const subject = `docs(pm): carry ${ahead} PM commits onto ${remoteRef}`;
  if (!worktree) {
    const commit = git(opts.root, ["commit-tree", tree, "-p", remoteRef, "-m", subject]);
    git(opts.root, ["branch", "-f", opts.pmBranch, commit]);
    return {
      action: "carried",
      moved: ahead,
      commit,
      message: `${opts.pmBranch} carried ${ahead} PM commits onto ${remoteRef} as ${commit.slice(0, 7)}; run pm-export on ${opts.pmBranch}.`,
    };
  }

  git(worktree, ["reset", "-q", "--keep", remoteRef]);
  try {
    git(worktree, ["read-tree", "-m", "-u", "HEAD", tree]);
    const refreshed = refreshExport(worktree, opts.pmRoot);
    git(worktree, ["add", "-A", "--", pm]);
    git(worktree, ["commit", "-q", "-m", subject, "--", pm]);
    const commit = git(worktree, ["rev-parse", "HEAD"]);
    return {
      action: "carried",
      moved: ahead,
      commit,
      message: `${opts.pmBranch} carried ${ahead} PM commits onto ${remoteRef} as ${commit.slice(0, 7)}${refreshed ? "" : `; run pm-export on ${opts.pmBranch}`}.`,
    };
  } catch (error) {
    return restore(error instanceof Error ? error.message : String(error));
  }
}

const ATTRIBUTE = (pm: string) => `${pm}/planning.json merge=pm-export`;

export function driver(opts: SyncOptions): SyncResult {
  const pm = dir(opts.pmRoot);
  const file = join(opts.root, ".gitattributes");
  const text = existsSync(file) ? readFileSync(file, "utf8") : "";
  const hasLine = text.split(/\r?\n/).some((line) => line.trim() === ATTRIBUTE(pm));
  const hasConfig = run(opts.root, ["config", "--get", "merge.pm-export.driver"]).stdout === "true";
  if (hasLine && hasConfig) return { action: "none", moved: 0, message: `Merge driver already registered for ${pm}/planning.json.` };
  if (!hasLine) {
    if (text === "") writeFileSync(file, `${ATTRIBUTE(pm)}\n`);
    else appendFileSync(file, `${text.endsWith("\n") ? "" : "\n"}${ATTRIBUTE(pm)}\n`);
  }
  git(opts.root, ["config", "merge.pm-export.name", "pm-export derived file"]);
  git(opts.root, ["config", "merge.pm-export.driver", "true"]);
  return { action: "registered", moved: 0, message: `Merge driver registered for ${pm}/planning.json.` };
}

/** Options from the command line, with defaults from `<PM root>/config.md` and git. */
function options(argv: string[]): SyncOptions {
  const flag = (name: string) => {
    const index = argv.indexOf(`--${name}`);
    return index >= 0 ? argv[index + 1] : undefined;
  };
  const root = resolve(flag("root") ?? ".");
  const pmRoot = flag("pm-root") ?? "planning/";
  const config = join(root, dir(pmRoot), "config.md");
  const configured = existsSync(config) ? /^- PM branch: *`?([^`\s]+)`?/m.exec(readFileSync(config, "utf8"))?.[1] : undefined;
  const pmBranch = flag("pm-branch") ?? configured ?? git(root, ["branch", "--show-current"]);
  let remote: string | null = flag("remote") ?? null;
  if (!remote) {
    const upstream = run(root, ["rev-parse", "--abbrev-ref", `${pmBranch}@{upstream}`]);
    if (upstream.status === 0 && upstream.stdout.includes("/")) remote = upstream.stdout.split("/")[0]!;
    else if (run(root, ["remote"]).stdout.split(/\r?\n/).includes("origin")) remote = "origin";
  }
  return { root, pmRoot, pmBranch, remote };
}

if (import.meta.main) {
  const [command, ...rest] = process.argv.slice(2);
  const commands: Record<string, (opts: SyncOptions) => SyncResult> = { release, pull, driver };
  const handler = command ? commands[command] : undefined;
  if (!handler) {
    console.error("usage: sync.ts <release|pull|driver> [--root <repo>] [--pm-root planning/] [--pm-branch <name>] [--remote <name>]");
    process.exit(2);
  }
  try {
    console.log(handler(options(rest)).message);
  } catch (error) {
    console.error(`sync: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}
